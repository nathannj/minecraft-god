import argparse
from functools import lru_cache
import os
from pathlib import Path
import shutil
import subprocess

from .runtime import workspace_root

TESTED_CODEX_VERSION = "0.151.0"
RUNTIME_CONFIG = '''# Generated by Minecraft God; use game environment variables to configure it.
cli_auth_credentials_store = "file"
approval_policy = "never"
sandbox_mode = "read-only"
web_search = "disabled"
notify = []

[features]
shell_tool = false
shell_snapshot = false
unified_exec = false
apps = false
browser_use = false
computer_use = false
plugins = false
hooks = false
image_generation = false
view_image = false
multi_agent = false
skill_search = false
skip_host_skill_discovery = true
code_mode_host = false
workspace_dependencies = false
'''


def codex_binary() -> str:
    binary = os.getenv("MINECRAFT_CODEX_CLI_PATH") or shutil.which("codex.cmd") or shutil.which("codex")
    if not binary:
        raise RuntimeError(f"Install Codex CLI: npm install -g @openai/codex@{TESTED_CODEX_VERSION}")
    return binary


@lru_cache(maxsize=4)
def check_version(binary: str) -> str:
    result = subprocess.run([binary, "--version"], capture_output=True, text=True, timeout=15, check=True)
    version = result.stdout.strip()
    if version != f"codex-cli {TESTED_CODEX_VERSION}":
        raise RuntimeError(f"Expected Codex CLI {TESTED_CODEX_VERSION}; found {version}. Set MINECRAFT_CODEX_CLI_PATH to a matching installation.")
    return version


def runtime_environment(root: Path) -> dict[str, str]:
    directory = root.resolve() / ".codex-runtime"
    directory.mkdir(parents=True, exist_ok=True)
    config = directory / "config.toml"
    if config.exists() and config.read_text(encoding="utf-8") != RUNTIME_CONFIG:
        raise RuntimeError("The generated .codex-runtime/config.toml was changed. Back it up, remove it, then retry; extra integrations are not supported.")
    if not config.exists():
        config.write_text(RUNTIME_CONFIG, encoding="utf-8")
    # This is Codex's documented per-process data-directory setting. It does
    # not change the parent's environment or the user's personal Codex home.
    environment = {key: value for key, value in os.environ.items() if not key.startswith("CODEX_")}
    environment["CODEX_HOME"] = str(directory)
    environment["MINECRAFT_GOD_HOME"] = str(root.resolve())
    return environment


def verify_mcp_inventory(client, thread_id: str) -> None:
    from .mcp_server import tool_definitions
    expected = {tool["name"] for tool in tool_definitions()}
    servers = []
    cursor = None
    for _ in range(20):
        params = {"threadId": thread_id, "limit": 100}
        if cursor:
            params["cursor"] = cursor
        page = client.request("mcpServerStatus/list", params, timeout=60)
        servers.extend(page.get("data", []))
        cursor = page.get("nextCursor")
        if not cursor:
            break
    else:
        raise RuntimeError("MCP inventory pagination exceeded its safety limit")
    if len(servers) != 1 or servers[0].get("name") != "minecraft_god":
        raise RuntimeError("God session refused: expected only the minecraft_god MCP server")
    tools = servers[0].get("tools", {})
    actual = set(tools) if isinstance(tools, dict) else {item.get("name") for item in tools}
    if actual != expected:
        raise RuntimeError("God session refused: Minecraft MCP tool inventory is missing or unexpected")


def protocol_check(root: Path) -> None:
    """Exercise the real app-server and MCP handshake without a model turn."""
    import tempfile
    from .controller import GodSession, Transcript
    from .mcp_server import tool_definitions
    tools_dir = root.resolve() / ".tools"
    tools_dir.mkdir(exist_ok=True)
    if not tools_dir.resolve().is_relative_to(root.resolve()):
        raise ValueError("verification directory must remain in the workspace")
    with tempfile.TemporaryDirectory(prefix="codex-protocol-check-", dir=tools_dir) as directory:
        temporary = Path(directory).resolve()
        if not temporary.is_relative_to(tools_dir.resolve()):
            raise ValueError("verification path escaped its intended directory")
        (temporary / "server").mkdir()
        (temporary / "server/rcon-password.txt").write_text("verification-only-no-live-server", encoding="utf-8")
        session = GodSession("a0d35179-5ead-4e3a-bef9-cdbb03bf306d", "Alice", temporary, Transcript(temporary), 120, start_worker=False)
        session.close()
    print(f"Protocol passed: read-only thread and {len(tool_definitions())} expected Minecraft MCP tools. No model turn started.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["check", "login", "status", "protocol-check"], default="check", nargs="?")
    args = parser.parse_args()
    try:
        binary = codex_binary()
        print(check_version(binary))
        if args.action == "protocol-check":
            protocol_check(workspace_root())
        elif args.action != "check":
            command = [binary, "login"] + (["status"] if args.action == "status" else [])
            result = subprocess.run(command, env=runtime_environment(workspace_root()), check=False)
            raise SystemExit(result.returncode)
    except (OSError, RuntimeError, subprocess.SubprocessError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
